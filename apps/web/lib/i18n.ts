export const webCatalogs = { es, en } as const

export function normalizeWebLocale(value: unknown, fallback: WebLocale = 'es'): WebLocale {
  if (typeof value !== 'string') return fallback
  const normalized = value.trim().toLowerCase().replaceAll('_', '-')
  if (normalized === 'es' || normalized.startsWith('es-')) return 'es'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return fallback
}

export function webLocaleName(locale: WebLocale, displayLocale: WebLocale = locale) {
  return webCatalogs[displayLocale][`language.${locale}`]
}

export function webT(locale: WebLocale, key: WebMessageKey, values: Record<string, string | number | null | undefined> = {}) {
  const template = webCatalogs[locale][key] ?? webCatalogs.es[key]
  return template.replace(/\{([a-zA-Z0-9_.-]+)\}/g, (_match, token: string) => {
    const value = values[token]
    return value === null || value === undefined ? `{${token}}` : String(value)
  })
}

export function webIntlLocale(locale: WebLocale) {
  return locale === 'en' ? 'en-US' : 'es-MX'
}
