import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = (path) => readFileSync(path, 'utf8')

const index = read('apps/bot/src/commands/index.ts')
const spotify = read('apps/bot/src/commands/spotify.ts')
const spotifyService = read('apps/bot/src/services/spotify.ts')
const sourceOverrides = read('apps/bot/src/commands/source-overrides-v7.ts')
const anime = read('apps/bot/src/services/anime.ts')
const adultDownloads = read('apps/bot/src/commands/adult-download-v15.ts')
const adultMode = read('apps/bot/src/commands/group-adult-mode.ts')
const adultRoleplay = read('apps/bot/src/commands/adult-roleplay-v8.ts')
const router = read('apps/bot/src/core/router.ts')
const esLocale = read('apps/bot/src/i18n/locales/es/default.ts')
const security = read('apps/bot/src/commands/security.ts')
const installer = read('scripts/install-windows.ps1')
const installerBytes = readFileSync('scripts/install-windows.ps1')
const manager = read('scripts/windows/ghostnexora.ps1')
const managerBytes = readFileSync('scripts/windows/ghostnexora.ps1')
const cmdInstaller = read('scripts/install-windows.cmd')
const waifuExtractor = read('scripts/extract-waifus.mjs')
const rootPackage = JSON.parse(read('package.json'))

assert.ok(index.includes("import { spotifyCommands } from './spotify.js'"), 'Spotify functional commands must be registered')
assert.match(spotify, /export async function spotifySearch/, 'Spotify search handler must be reusable by the legacy command slot')
assert.match(sourceOverrides, /handler: spotifySearch/, 'The canonical Spotify command must use the functional search handler')
assert.match(spotify, /name: 'spotifydl'/, 'spotifydl command missing')
assert.match(spotifyService, /https:\/\/accounts\.spotify\.com\/api\/token/, 'Spotify Client Credentials token flow missing')
assert.match(spotifyService, /\/v1\/search\?type=track/, 'Spotify track search endpoint missing')

assert.match(anime, /https:\/\/api\.jikan\.moe\/v4\/anime/, 'Jikan metadata integration missing')
assert.match(anime, /api\/v1\/anime\/search/, 'Anime1v search integration missing')
assert.match(anime, /encodeRef\(/, 'Anime provider provenance encoding missing')
assert.doesNotMatch(anime, /command -v/, 'Anime downloader availability check must remain cross-platform')

assert.doesNotMatch(adultDownloads, /staffOnly\s*:\s*true/, 'Public adult download commands must not be staff-only')
assert.doesNotMatch(adultDownloads, /ownerOnly\s*:\s*true/, 'Public adult download commands must not be owner-only')
assert.match(adultMode, /setGroupCategoryOverride\(ctx\.chatId, 'adult', enabled \? 'allow' : 'deny'\)/, 'adultmode must synchronize router category policy')
assert.match(security, /setGroupCategoryOverride\(ctx\.chatId, 'adult', enabled \? 'allow' : 'deny'\)/, 'nsfw must synchronize router category policy')
assert.match(adultRoleplay, /isRateOverlimit/, 'Adult roleplay must detect WhatsApp rate-overlimit errors')
assert.match(adultRoleplay, /for \(const delay of \[0, 2500, 5000\]\)/, 'Adult roleplay must retry text delivery with bounded backoff')
assert.match(adultRoleplay, /sendMediaOrTextFallback/, 'Adult roleplay media delivery must fall back to text on WhatsApp rate limits')
assert.match(router, /router\.rateLimited/, 'Router must not expose raw rate-overlimit strings')
assert.match(router, /react\('⚡'\)\.catch\(\(\) => undefined\)/, 'Command start reactions must not abort command execution when WhatsApp throttles reactions')
assert.match(router, /react\('✅'\)\.catch\(\(\) => undefined\)/, 'Success reactions must not turn an already-completed command into a failure')
assert.match(esLocale, /'router\.rateLimited'/, 'Spanish rate-limit explanation missing')

assert.deepEqual(Array.from(installerBytes.subarray(0, 3)), [0xef, 0xbb, 0xbf], 'Windows installer must keep a UTF-8 BOM for Windows PowerShell 5.1')
assert.doesNotMatch(installer, /Cierra PowerShell/i, 'Windows installer must not require closing the terminal')
assert.match(installer, /Repair-CommandPath/, 'Windows installer must repair PATH in the same process')
assert.match(installer, /function Test-WinGetPackageInstalled/, 'Windows installer must detect packages that WinGet already has installed')
assert.match(installer, /WinGet terminó con código \$wingetExit, pero \$Label ya está instalado/, 'Windows installer must treat already-current WinGet packages as non-fatal')
assert.match(installer, /ghostnexora doctor puede revisarlo después/, 'Windows installer must continue when an installed package command is temporarily missing from PATH')
assert.match(installer, /managerPath configure/, 'Windows installer must open the post-install configuration menu')
assert.doesNotMatch(installer, /managerPath start/, 'Windows installer must not auto-start MainBot')
assert.match(installer, /Write-Banner/, 'Windows installer must keep the decorative guided console')
assert.match(installer, /Read-YesNo/, 'Windows installer must ask explicit optional-component questions')
assert.match(installer, /UBICACIÓN DE INSTALACIÓN/, 'Windows installer must offer an explicit install-location step')
assert.match(installer, /Current-InstallSuggestion/, 'Windows installer must support installing relative to the current drive/folder')
assert.match(installer, /Elegir otra ruta manualmente/, 'Windows installer must support an arbitrary custom installation path')
assert.match(installer, /GhostNexoraBotData/, 'Windows installer must support persistent data on the selected drive instead of forcing LOCALAPPDATA')
assert.match(installer, /GHOST_NEXORA_HOME/, 'Windows installer must persist the selected code path for the manager')
assert.match(installer, /GHOST_NEXORA_STATE/, 'Windows installer must persist the selected data path for the manager')
assert.match(installer, /WEB_EXPOSURE/, 'Windows installer must persist local/public/disabled Web exposure mode')
assert.match(installer, /MODO DE ACCESO WEB/, 'Windows installer must offer Local/Public Web modes')
assert.match(installer, /http:\/\/127\.0\.0\.1:\$selectedPort/, 'Local Web mode must show the localhost URL and selected port')
assert.match(installer, /La Web pública debe usar HTTPS/, 'Public Web mode must enforce HTTPS')
assert.match(installer, /DNS \+ HTTPS \+ reverse proxy\/túnel/, 'Public Web mode must explain its external networking requirement')
assert.match(installer, /install-error\.log/, 'Windows installer must persist detailed installation errors')
assert.match(installer, /Paso: \$CurrentStep/, 'Windows installer error log must identify the failing step')
assert.match(installer, /Etapa: \$CurrentStage/, 'Windows installer error log must identify the failing stage')
assert.match(installer, /Código: \$\(\$Record\.InvocationInfo\.Line\)/, 'Windows installer error log must include the failing code line')
assert.match(installer, /Get-Content -LiteralPath \$managerSource -Raw -Encoding UTF8/, 'Windows installer must decode the manager source explicitly as UTF-8')
assert.match(installer, /Set-Content -LiteralPath \$managerTarget -Value \$managerContent -Encoding UTF8/, 'Windows installer must write the installed manager with a PowerShell 5.1 UTF-8 BOM')
assert.deepEqual(Array.from(managerBytes.subarray(0, 3)), [0xef, 0xbb, 0xbf], 'Windows manager must keep a UTF-8 BOM for Windows PowerShell 5.1')
assert.match(manager, /'configure' \{ Configure-Bot \}/, 'Windows manager configure action missing')
assert.match(manager, /developer\.spotify\.com\/dashboard/, 'Windows configuration menu must explain Spotify credentials')
assert.match(cmdInstaller, /pause/i, 'CMD wrapper must keep the terminal visible at completion')
assert.match(cmdInstaller, /GHOST_NEXORA_INSTALLER_WRAPPER=1/, 'CMD wrapper must identify the persistent console session')
assert.match(cmdInstaller, /Get-Content -LiteralPath \$p -Raw -Encoding UTF8/, 'CMD bootstrap must decode the downloaded script explicitly as UTF-8')
assert.match(cmdInstaller, /Set-Content -LiteralPath \$p -Value \$text -Encoding UTF8/, 'CMD bootstrap must rewrite the downloaded script with a Windows PowerShell 5.1 BOM')
assert.match(cmdInstaller, /Language\.Parser\]::ParseFile/, 'CMD bootstrap must syntax-check the downloaded script before execution')
assert.doesNotMatch(cmdInstaller, /\^\|/, 'CMD bootstrap parser preflight must not depend on escaped pipe semantics inside -Command')
assert.doesNotMatch(cmdInstaller, /^start\s/mi, 'CMD wrapper must not detach into a disposable window')

assert.equal(rootPackage.allowScripts?.['baileys@7.0.0-rc14'], true, 'Baileys install script must be explicitly approved')
assert.equal(rootPackage.allowScripts?.['esbuild@0.28.2'], true, 'esbuild install script must be explicitly approved')
assert.equal(rootPackage.allowScripts?.['protobufjs@7.6.6'], true, 'protobufjs install script must be explicitly approved')
assert.match(installer, /npm\.cmd rebuild baileys esbuild protobufjs/, 'Windows installer must repair dependencies whose install scripts were previously blocked')
assert.match(waifuExtractor, /process\.platform === 'win32'/, 'Waifu extractor must have a native Windows path')
assert.match(waifuExtractor, /System\.IO\.Compression\.ZipFile/, 'Windows waifu extraction must use built-in .NET ZIP support')
assert.doesNotMatch(waifuExtractor, /Se requiere el comando unzip para preparar los assets locales de waifus\.'/, 'Windows build must not require external unzip')

console.log('Spotify, anime, adult permissions and Windows installer smoke passed')
